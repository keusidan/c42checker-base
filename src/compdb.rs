use crate::args::{extra_cflags, shell_split};
use crate::exec::{exec_cmd, ExecOptions};
use crate::sources::find_makefile;
use crate::types::{CompdbSource, Context};
use serde::{Deserialize, Serialize};
use std::collections::HashSet;
use std::fs;
use std::path::{Path, PathBuf};

pub const CLANGD_MARKER: &str = "# generated by c42checker";
pub const STATE_DIR: &str = "state";
const COMPDB_VERSION: u32 = 1;

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct CompdbEntry {
    pub directory: String,
    pub file: String,
    pub arguments: Vec<String>,
}

#[derive(Debug, Clone)]
pub struct CompdbResult {
    pub method: CompdbSource,
    pub entries: usize,
    pub note: Option<String>,
}

fn is_compiler_token(tok: &str) -> bool {
    let base = tok.rsplit('/').next().unwrap_or(tok);
    matches!(base, "cc" | "c99" | "gcc" | "clang")
        || base.starts_with("gcc-")
        || base.starts_with("clang-")
        || base.ends_with("-gcc")
}

fn is_keep_with_value(tok: &str) -> bool {
    matches!(
        tok,
        "-I" | "-D" | "-U" | "-include" | "-isystem" | "-iquote" | "-idirafter"
    )
}

fn is_skip_with_value(tok: &str) -> bool {
    matches!(tok, "-o" | "-MF" | "-MT" | "-MQ")
}

fn is_keep_prefix(tok: &str) -> bool {
    if tok.starts_with("-Wl,") {
        return false;
    }
    tok.starts_with("-I")
        || tok.starts_with("-D")
        || tok.starts_with("-U")
        || tok.starts_with("-O")
        || tok.starts_with("-g")
        || tok.starts_with("-std=")
        || tok.starts_with("-m")
        || tok.starts_with("-f")
        || tok == "-pthread"
        || tok.starts_with("-isystem")
        || tok.starts_with("-iquote")
        || tok.starts_with("-idirafter")
        || tok.starts_with("-include")
        || tok.starts_with("-W")
}

pub fn parse_make_dry_run(output: &str, root: &Path) -> Vec<CompdbEntry> {
    let joined = output.replace("\\\r\n", " ").replace("\\\n", " ");
    let mut stack: Vec<PathBuf> = vec![root.to_path_buf()];
    let mut entries = Vec::new();
    let mut seen = HashSet::new();

    for line in joined.lines() {
        if let Some(idx) = line.find("Entering directory ") {
            let rest = &line[idx + 19..];
            if let Some(dir) = rest
                .trim()
                .trim_start_matches(['\'', '`'])
                .strip_suffix('\'')
            {
                stack.push(PathBuf::from(dir));
                continue;
            }
        }
        if line.contains("Leaving directory") {
            if stack.len() > 1 {
                stack.pop();
            }
            continue;
        }
        let cur_dir = stack.last().cloned().unwrap_or_else(|| root.to_path_buf());
        for seg in split_shell_separators(line) {
            let mut tokens = shell_split(seg.trim());
            while !tokens.is_empty() && tokens[0].contains('=') && !tokens[0].starts_with('-') {
                tokens.remove(0);
            }
            if tokens.is_empty() || !is_compiler_token(&tokens[0]) {
                continue;
            }
            let cc = tokens[0].clone();
            let mut flags = Vec::new();
            let mut files = Vec::new();
            let mut i = 1;
            while i < tokens.len() {
                let a = &tokens[i];
                if is_skip_with_value(a) {
                    i += 2;
                    continue;
                }
                if is_keep_with_value(a) {
                    flags.push(a.clone());
                    if i + 1 < tokens.len() {
                        flags.push(tokens[i + 1].clone());
                    }
                    i += 2;
                    continue;
                }
                if a == "-c" || a.starts_with("-M") || a.starts_with("-l") || a.starts_with("-L") {
                    i += 1;
                    continue;
                }
                if is_keep_prefix(a) {
                    flags.push(a.clone());
                    i += 1;
                    continue;
                }
                if !a.starts_with('-') && a.ends_with(".c") {
                    files.push(cur_dir.join(a));
                }
                i += 1;
            }
            for f in files {
                let key = f.to_string_lossy().into_owned();
                if seen.insert(key.clone()) {
                    let mut args = vec![cc.clone()];
                    args.extend(flags.clone());
                    args.push("-c".to_string());
                    args.push(key.clone());
                    entries.push(CompdbEntry {
                        directory: cur_dir.to_string_lossy().into_owned(),
                        file: key,
                        arguments: args,
                    });
                }
            }
        }
    }
    entries
}

fn split_shell_separators(line: &str) -> Vec<&str> {
    let mut out = Vec::new();
    let mut start = 0;
    let bytes = line.as_bytes();
    let mut i = 0;
    let mut quote: Option<u8> = None;
    while i < bytes.len() {
        let b = bytes[i];
        if let Some(q) = quote {
            if b == q {
                quote = None;
            } else if b == b'\\' && q == b'"' {
                i += 1;
            }
            i += 1;
            continue;
        }
        if b == b'"' || b == b'\'' {
            quote = Some(b);
            i += 1;
            continue;
        }
        if b == b';' || b == b'|' || (b == b'&' && i + 1 < bytes.len() && bytes[i + 1] == b'&') {
            out.push(&line[start..i]);
            if (b == b'|' || b == b'&') && i + 1 < bytes.len() && bytes[i + 1] == b {
                i += 2;
            } else {
                i += 1;
            }
            start = i;
            continue;
        }
        i += 1;
    }
    if start <= line.len() {
        out.push(&line[start..]);
    }
    out
}

pub fn entries_from_files(ctx: &Context) -> Vec<CompdbEntry> {
    let cc = ctx.tools.cc.clone().unwrap_or_else(|| "clang".to_string());
    let mut flags = vec![
        "-Wall".to_string(),
        "-Wextra".to_string(),
        "-Werror".to_string(),
    ];
    for d in &ctx.include_dirs {
        flags.push(format!("-I{}", d.display()));
    }
    flags.extend(extra_cflags(ctx));

    let mut files = ctx.sources.clone();
    if ctx.settings.compdb_include_main {
        if let Some(ref mf) = ctx.main_file {
            if !files.contains(mf) {
                files.push(mf.clone());
            }
        }
    }

    files
        .into_iter()
        .map(|f| {
            let f_str = f.to_string_lossy().into_owned();
            let mut args = vec![cc.clone()];
            args.extend(flags.clone());
            args.push("-c".to_string());
            args.push(f_str.clone());
            CompdbEntry {
                directory: ctx.root.to_string_lossy().into_owned(),
                file: f_str,
                arguments: args,
            }
        })
        .collect()
}

pub fn generate_compdb(ctx: &Context) -> Result<CompdbResult, String> {
    let source = ctx.settings.compdb_source;
    let makefile = if ctx.settings.ignore_makefile {
        None
    } else {
        find_makefile(&ctx.target_root)
    };

    let (entries, method, note) = if (source == CompdbSource::Auto || source == CompdbSource::MakeN)
        && makefile.is_some()
        && ctx.tools.make.is_some()
    {
        let make_bin = ctx.tools.make.as_deref().unwrap();
        let res = exec_cmd(
            make_bin,
            &["-n".into(), "-B".into(), "-w".into()],
            &ExecOptions {
                cwd: &ctx.target_root,
                timeout_ms: 15_000,
                cancelled: Some(ctx.cancelled.clone()),
                force_c_locale: true,
            },
        );
        let parsed = parse_make_dry_run(&res.output, &ctx.target_root);
        if !parsed.is_empty() {
            (parsed, CompdbSource::MakeN, None)
        } else {
            (
                entries_from_files(ctx),
                CompdbSource::Files,
                Some("make -n からコンパイルコマンドを抽出できなかったため files 方式で生成しました".to_string()),
            )
        }
    } else {
        (entries_from_files(ctx), CompdbSource::Files, None)
    };

    let json = serde_json::to_string_pretty(&entries).map_err(|e| e.to_string())?;
    fs::write(ctx.root.join("compile_commands.json"), format!("{json}\n"))
        .map_err(|e| e.to_string())?;

    Ok(CompdbResult {
        method,
        entries: entries.len(),
        note,
    })
}

pub fn clangd_content() -> String {
    format!(
        "{CLANGD_MARKER}\nCompileFlags:\n  Add:\n    - -Wall\n    - -Wextra\n"
    )
}

pub fn generate_clangd(root: &Path) -> (bool, Option<String>) {
    let path = root.join(".clangd");
    if path.exists() {
        let existing = fs::read_to_string(&path).unwrap_or_default();
        if !existing.starts_with(CLANGD_MARKER) {
            return (
                false,
                Some("既存の .clangd (c42checker 以外が作成) は上書きしませんでした".to_string()),
            );
        }
    }
    let _ = fs::write(&path, clangd_content());
    (true, None)
}

fn fnv1a_hex(s: &str) -> String {
    let mut h: u64 = 0xcbf29ce484222325;
    for b in s.as_bytes() {
        h ^= *b as u64;
        h = h.wrapping_mul(0x100000001b3);
    }
    format!("{h:016x}")
}

pub fn compdb_fingerprint(ctx: &Context) -> String {
    let mut payload = format!("v={COMPDB_VERSION}\n");
    payload.push_str(&format!("src={:?}\n", ctx.settings.compdb_source));
    payload.push_str(&format!("inc_main={}\n", ctx.settings.compdb_include_main));
    payload.push_str(&format!("ignore_mk={}\n", ctx.settings.ignore_makefile));
    for d in &ctx.include_dirs {
        payload.push_str(&format!("I:{}\n", d.display()));
    }
    for f in &ctx.sources {
        payload.push_str(&format!("S:{}\n", f.display()));
    }
    if let Some(ref mf) = ctx.main_file {
        payload.push_str(&format!("M:{}\n", mf.display()));
    }
    for c in extra_cflags(ctx) {
        payload.push_str(&format!("C:{c}\n"));
    }
    fnv1a_hex(&payload)
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum EnsureAction {
    Generated,
    Regenerated,
    Unchanged,
    Foreign,
}

pub struct EnsureResult {
    pub action: EnsureAction,
    pub result: Option<CompdbResult>,
    pub clangd_written: bool,
    pub clangd_reason: Option<String>,
}

pub fn ensure_generated(ctx: &Context, force: bool) -> Result<EnsureResult, String> {
    let compdb_path = ctx.root.join("compile_commands.json");
    let state_dir = ctx.work_dir.join(STATE_DIR);
    let stamp_path = state_dir.join("compdb.stamp");
    let fp = compdb_fingerprint(ctx);

    let (clangd_written, clangd_reason) = generate_clangd(&ctx.root);

    if !force && compdb_path.is_file() {
        if let Ok(old_fp) = fs::read_to_string(&stamp_path) {
            if old_fp.trim() == fp {
                return Ok(EnsureResult {
                    action: EnsureAction::Unchanged,
                    result: None,
                    clangd_written,
                    clangd_reason,
                });
            }
            let res = generate_compdb(ctx)?;
            let _ = fs::create_dir_all(&state_dir);
            let _ = fs::write(&stamp_path, &fp);
            return Ok(EnsureResult {
                action: EnsureAction::Regenerated,
                result: Some(res),
                clangd_written,
                clangd_reason,
            });
        } else {
            return Ok(EnsureResult {
                action: EnsureAction::Foreign,
                result: None,
                clangd_written,
                clangd_reason,
            });
        }
    }

    let action = if compdb_path.is_file() {
        EnsureAction::Regenerated
    } else {
        EnsureAction::Generated
    };
    let res = generate_compdb(ctx)?;
    let _ = fs::create_dir_all(&state_dir);
    let _ = fs::write(&stamp_path, &fp);
    Ok(EnsureResult {
        action,
        result: Some(res),
        clangd_written,
        clangd_reason,
    })
}
